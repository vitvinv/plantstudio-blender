def make_default_params():
    """Build PlantParams with every parameter at the original PlantStudio defaults."""
    from .params import PlantParams
    from .pla_parser import set_param, registry_by_id
    from .tdo_parser import parse_tdo_compact
    from .normalize import normalize_params

    params = PlantParams()
    reg = registry_by_id()
    for kid, value in DEFAULT_PARAMS.items():
        entry = reg.get(kid)
        if entry is None:
            continue
        ftype = entry["type"]
        tdo = parse_tdo_compact(value) if ftype == 5 else None
        set_param(params, entry["access"], ftype, value, tdo)
    normalize_params(params)
    return params
